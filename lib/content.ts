function dayOfYear(date: Date) {
  return Math.floor(
    (date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / 86400000
  );
}

export function pickByDay<T>(arr: T[], date: Date, offset = 0): T {
  const idx = (dayOfYear(date) + offset) % arr.length;
  return arr[idx];
}

